import { compileRecordLayouts } from './schema.mjs';

export function generateCppHeader(data) {
  const { layouts, layoutHash } = compileRecordLayouts();
  const { enums, ages, resources, sensors, weapons, units, buildings, techs } = data;

  const lines = [];

  lines.push('// AUTO-GENERATED BY schema_compiler/codegen_cpp.mjs - DO NOT EDIT DIRECTLY');
  lines.push('#pragma once');
  lines.push('');
  lines.push('#include "core/types.hpp"');
  lines.push('#include "core/fixed_math.hpp"');
  lines.push('#include <type_traits>');
  lines.push('#include <cstddef>');
  lines.push('');
  lines.push('namespace ron::db {');
  lines.push('');
  lines.push(`inline constexpr u64 LAYOUT_HASH = 0x${layoutHash.toString(16).padStart(16, '0')}ULL;`);
  lines.push('inline constexpr u32 DB_MAGIC = 0x444E4F52; // "ROND"');
  lines.push('inline constexpr u32 DB_VERSION = 1;');
  lines.push('inline constexpr u16 NONE16 = 0xFFFF;');
  lines.push('inline constexpr u8  NONE8  = 0xFF;');
  lines.push('');

  // Enums
  const standardEnums = [
    ['DamageArchetype', 'u8'],
    ['GuidanceType', 'u8'],
    ['SensorBand', 'u8'],
    ['UnitClass', 'u8'],
    ['TechPillar', 'u8'],
    ['TechEffectOp', 'u8'],
    ['MovementDomain', 'u8']
  ];

  for (const [enumName, underlying] of standardEnums) {
    if (enums[enumName]) {
      lines.push(`enum class ${enumName} : ${underlying} {`);
      const values = enums[enumName];
      for (let i = 0; i < values.length; i++) {
        const comma = (i === values.length - 1) ? '' : ',';
        lines.push(`    ${values[i]} = ${i}${comma}`);
      }
      lines.push('};');
      lines.push('');
    }
  }

  // Flags namespaces
  if (enums.UnitFlag) {
    lines.push('namespace UnitFlag {');
    enums.UnitFlag.forEach((f, i) => {
      lines.push(`    inline constexpr u32 ${f} = 1u << ${i};`);
    });
    lines.push('}');
    lines.push('');
  }

  if (enums.WeaponFlag) {
    lines.push('namespace WeaponFlag {');
    enums.WeaponFlag.forEach((f, i) => {
      lines.push(`    inline constexpr u16 ${f} = static_cast<u16>(1u << ${i});`);
    });
    lines.push('}');
    lines.push('');
  }

  if (enums.BuildingFlag) {
    lines.push('namespace BuildingFlag {');
    enums.BuildingFlag.forEach((f, i) => {
      lines.push(`    inline constexpr u32 ${f} = 1u << ${i};`);
    });
    lines.push('}');
    lines.push('');
  }

  // Header and Section Table structs
  lines.push('struct DbHeader {');
  lines.push('    u32 magic{0};');
  lines.push('    u32 schema_version{0};');
  lines.push('    u64 layout_hash{0};');
  lines.push('    u64 content_xxh64{0};');
  lines.push('    u32 total_file_size{0};');
  lines.push('    u32 section_count{0};');
  lines.push('    u32 string_table_offset{0};');
  lines.push('    u32 string_table_size{0};');
  lines.push('    u8 _pad[24]{0};');
  lines.push('};');
  lines.push('static_assert(sizeof(DbHeader) == 64);');
  lines.push('static_assert(offsetof(DbHeader, magic) == 0);');
  lines.push('static_assert(offsetof(DbHeader, schema_version) == 4);');
  lines.push('static_assert(offsetof(DbHeader, layout_hash) == 8);');
  lines.push('static_assert(offsetof(DbHeader, content_xxh64) == 16);');
  lines.push('static_assert(offsetof(DbHeader, total_file_size) == 24);');
  lines.push('static_assert(offsetof(DbHeader, section_count) == 28);');
  lines.push('static_assert(offsetof(DbHeader, string_table_offset) == 32);');
  lines.push('static_assert(offsetof(DbHeader, string_table_size) == 36);');
  lines.push('static_assert(offsetof(DbHeader, _pad) == 40);');
  lines.push('static_assert(std::has_unique_object_representations_v<DbHeader>);');
  lines.push('');

  lines.push('struct DbSectionEntry {');
  lines.push('    u32 offset{0};');
  lines.push('    u32 count{0};');
  lines.push('    u32 stride{0};');
  lines.push('    u32 pad{0};');
  lines.push('};');
  lines.push('static_assert(sizeof(DbSectionEntry) == 16);');
  lines.push('static_assert(offsetof(DbSectionEntry, offset) == 0);');
  lines.push('static_assert(offsetof(DbSectionEntry, count) == 4);');
  lines.push('static_assert(offsetof(DbSectionEntry, stride) == 8);');
  lines.push('static_assert(offsetof(DbSectionEntry, pad) == 12);');
  lines.push('static_assert(std::has_unique_object_representations_v<DbSectionEntry>);');
  lines.push('');

  // Generated DB record structs
  for (const [structName, layout] of Object.entries(layouts)) {
    lines.push(`struct ${structName} {`);
    for (const f of layout.fields) {
      if (f.isPad) {
        if (f.count && f.count > 1) {
          lines.push(`    u8 ${f.name}[${f.count}]{0};`);
        } else {
          lines.push(`    u8 ${f.name}{0};`);
        }
      } else if (f.isFixedArray) {
        const cppType = f.elemCpp === 'fx32' ? '::ron::fx32' : f.elemCpp;
        lines.push(`    ${cppType} ${f.name}[${f.count}]{0};`);
      } else {
        const cppType = f.cpp === 'fx32' ? '::ron::fx32' : f.cpp;
        lines.push(`    ${cppType} ${f.name}{0};`);
      }
    }
    lines.push('};');
    lines.push(`static_assert(sizeof(${structName}) == ${layout.size});`);
    lines.push(`static_assert(std::has_unique_object_representations_v<${structName}>);`);
    for (const f of layout.fields) {
      lines.push(`static_assert(offsetof(${structName}, ${f.name}) == ${f.offset});`);
    }
    lines.push('');
  }

  // ID Constants
  const idGroups = [
    ['age_id', 'u8', ages],
    ['res_id', 'u8', resources],
    ['sensor_id', 'u16', sensors],
    ['weapon_id', 'u16', weapons],
    ['unit_id', 'u16', units],
    ['building_id', 'u16', buildings],
    ['tech_id', 'u16', techs]
  ];

  for (const [nsName, typeName, list] of idGroups) {
    lines.push(`namespace ${nsName} {`);
    list.forEach((item, idx) => {
      lines.push(`    inline constexpr ${typeName} ${item.id} = ${idx};`);
    });
    lines.push('}');
    lines.push('');
  }

  lines.push('} // namespace ron::db');
  lines.push('');

  return lines.join('\n');
}
